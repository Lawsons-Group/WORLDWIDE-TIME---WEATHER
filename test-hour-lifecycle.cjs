const { readFileSync } = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const node = () => ({ textContent:'', handlers:{}, attributes:{}, addEventListener(n,f){this.handlers[n]=f;}, setAttribute(n,v){this.attributes[n]=v;}, append(){}, appendChild(){}, replaceChildren(){}, focus(){} });
const detailIds=['hourDetailTitle','hourDetailPlace','hourDetailCondition','hourDetailIcon','hourDetailGrid'];
const nodes=Object.fromEntries([...detailIds,'hourDetails','hourly','closeHourDetails'].map(id=>[id,node()]));
const panel=nodes.hourDetails, hourly=nodes.hourly;
let attached=true, cards=[], timers=new Map(), timer=0;
panel.classList={add(){},remove(){}};
panel.querySelector=selector=>nodes[selector.slice(1)];
panel.scrollIntoView=()=>{};
hourly.querySelector=selector=>cards.find(card=>card.dataset.hourIndex===selector.match(/"(.*?)"/)[1]);
hourly.querySelectorAll=()=>cards;
function rebuild(){
  attached=false;
  cards=[0,1].map(index=>({ ...node(), dataset:{hourIndex:String(index)}, after(){attached=true;}, closest(){return this;}, querySelector(){return {textContent:'☀',getAttribute(){return 'Clear skies';}};} }));
}
const document={ getElementById(id){return detailIds.includes(id)&&!attached?null:nodes[id];},createElement:node };
const context={document,window:{matchMedia(){return {matches:true};}},Intl,Date,Number,setTimeout(fn){timers.set(++timer,fn);return timer;},clearTimeout(id){timers.delete(id);}};
vm.runInNewContext(readFileSync('dist/hour-details.js','utf8'),context);
const api=context.window.HourDetails;
const forecast={time:[3600,7200],temperature_2m:[10,12],apparent_temperature:[8,10]};
rebuild();api.setForecast(forecast,'UTC','c','London');
const click=index=>hourly.handlers.click({target:cards[index]});
click(0);
assert.equal(attached,true);
assert.equal(nodes.hourDetailTitle.textContent.includes('01:00'),true);
rebuild();
assert.doesNotThrow(()=>api.setForecast(forecast,'UTC','f','London'),'Refresh must work when an open panel is detached');
assert.equal(attached,true);
assert.equal(cards[0].attributes['aria-expanded'],'true');
nodes.closeHourDetails.handlers.click();
rebuild();api.setForecast(forecast,'UTC','f','London');
assert.doesNotThrow(()=>click(1),'Closed panel must reopen after forecast redraw');
assert.equal(attached,true);
assert.equal(cards[1].attributes['aria-expanded'],'true');
assert.match(nodes.hourDetailTitle.textContent,/02:00/);
click(1);
assert.equal(cards[1].attributes['aria-expanded'],'false','Clicking the same hour collapses it');
console.log('Passed: open and closed panels survive forecast redraws, unit changes and reopening.');
